// 행정구역 개편 전 코드: 강원(42→51), 전북(45→52), 군위(경북 47720→대구 27720)
const LEGACY = { 51: '42', 52: '45' }
const EXTRA_CODES = { 27720: ['47720'] }

export const ACCIDENT_REGIONS = Object.entries(SIDO).flatMap(([sido, [sidoName, list]]) =>
  list.split(',').map(entry => {
    const [gugun, ...name] = entry.split(' ')
    const code = sido + gugun
    const codes = [code, ...(LEGACY[sido] ? [LEGACY[sido] + gugun] : []), ...(EXTRA_CODES[code] || [])]
    return { code, name: `${sidoName} ${name.join(' ')}`, codes }
  }))

export const DAEJEON_REGIONS = ACCIDENT_REGIONS.filter(r => r.code.startsWith('30'))
